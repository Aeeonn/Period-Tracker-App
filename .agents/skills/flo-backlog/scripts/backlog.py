#!/usr/bin/env python3
"""Flo backlog tool for docs/plan/backlog.md (replaces Firstmate's tasks-axi backend for Flo).

Usage:
  backlog.py check                      validate fields, statuses, dependencies, cycles and board sync
  backlog.py ready                      queued items whose dependencies are all satisfied and that have no hold
  backlog.py board [--write]            print (or rewrite) the generated board section
  backlog.py show <id>                  print one item block
  backlog.py set <id> <field> <value>   set or add one field line, stamp `updated`, rewrite the board
  backlog.py add <id> --title T --kind ship|scout|gate [--type X] [--phase P] [--risk R]
                 [--blocked-by a,b] [--owns X] [--route X] [--notes X] [--status S]
Options: --file PATH (default: $FLO_REPO/docs/plan/backlog.md, FLO_REPO defaulting to ~/code/flo,
         the primary checkout, whatever the current directory is)

A dependency is satisfied when its status is `done` or `superseded`. Exception: `<ship>-verify`
may start once `<ship>` is in flight with a `candidate` field (the exact SHA to review).
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import sys
from pathlib import Path

STATUSES = ("queued", "in-flight", "held", "blocked", "done", "superseded", "cancelled")
SATISFIED = ("done", "superseded")
KINDS = ("ship", "scout", "gate")
REQUIRED = ("title", "status", "kind", "phase", "risk", "blocked-by")
BOARD_START = "<!-- board:start (generated by backlog.py; do not edit by hand) -->"
BOARD_END = "<!-- board:end -->"
ITEMS_HEADING = "## Items"
FIELD_RE = re.compile(r"^- ([a-z][a-z0-9-]*): ?(.*)$")
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
EMPTY = ("", "—", "-", "none")


def default_file() -> Path:
    # Always the primary checkout's backlog, never a task slot's copy (cwd is ignored).
    repo = os.environ.get("FLO_REPO") or str(Path.home() / "code" / "flo")
    return Path(repo) / "docs" / "plan" / "backlog.md"


class Item:
    def __init__(self, item_id: str, start: int, end: int, lines: list[str]):
        self.id = item_id
        self.start = start
        self.end = end
        self.fields: dict[str, str] = {}
        for line in lines[start + 1 : end]:
            m = FIELD_RE.match(line)
            if m:
                self.fields[m.group(1)] = m.group(2).strip()

    def get(self, key: str) -> str:
        return self.fields.get(key, "")

    @property
    def deps(self) -> list[str]:
        raw = self.get("blocked-by")
        if raw in EMPTY:
            return []
        return [d.strip(" `") for d in raw.split(",") if d.strip(" `")]


class Backlog:
    def __init__(self, path: Path):
        self.path = path
        self.lines = path.read_text(encoding="utf-8").split("\n")
        self.parse()

    def parse(self) -> None:
        try:
            self.items_at = self.lines.index(ITEMS_HEADING)
        except ValueError:
            sys.exit(f"error: {self.path} has no '{ITEMS_HEADING}' heading")
        self.items_end = len(self.lines)
        for i in range(self.items_at + 1, len(self.lines)):
            if self.lines[i].startswith("## "):
                self.items_end = i
                break
        heads = [i for i in range(self.items_at + 1, self.items_end) if self.lines[i].startswith("### ")]
        self.items: dict[str, Item] = {}
        self.order: list[str] = []
        for n, start in enumerate(heads):
            end = heads[n + 1] if n + 1 < len(heads) else self.items_end
            item_id = self.lines[start][4:].strip()
            if item_id in self.items:
                sys.exit(f"error: duplicate item id {item_id}")
            self.items[item_id] = Item(item_id, start, end, self.lines)
            self.order.append(item_id)

    def save(self) -> None:
        self.path.write_text("\n".join(self.lines), encoding="utf-8")

    def item(self, item_id: str) -> Item:
        if item_id not in self.items:
            sys.exit(f"error: no item {item_id}")
        return self.items[item_id]

    def satisfied(self, dep: str, for_item: str = "") -> bool:
        if dep not in self.items:
            return False
        it = self.items[dep]
        if it.get("status") in SATISFIED:
            return True
        # A `<ship>-verify` item may start once its ship item records a ready candidate.
        return (
            for_item == f"{dep}-verify"
            and it.get("status") == "in-flight"
            and it.get("candidate") not in EMPTY
        )

    def ready(self) -> list[Item]:
        return [
            self.items[i]
            for i in self.order
            if self.items[i].get("status") == "queued"
            and self.items[i].get("hold") in EMPTY
            and all(self.satisfied(d, i) for d in self.items[i].deps)
        ]

    def board(self) -> list[str]:
        counts: dict[str, int] = {}
        for it in self.items.values():
            counts[it.get("status")] = counts.get(it.get("status"), 0) + 1

        def ids(statuses: tuple[str, ...]) -> str:
            found = [f"`{i}`" for i in self.order if self.items[i].get("status") in statuses]
            return ", ".join(found) or "none"

        out = [
            BOARD_START,
            "",
            "- **Counts:** " + " · ".join(f"{s} {counts[s]}" for s in STATUSES if counts.get(s)),
            f"- **In flight / blocked:** {ids(('in-flight', 'blocked'))}",
            f"- **Held for the captain:** {ids(('held',))}",
            "- **Ready to dispatch:** " + (", ".join(f"`{it.id}`" for it in self.ready()) or "none"),
            "",
            "| Item | Status | Kind | Risk | Phase | Blocked by |",
            "|---|---|---|---|---|---|",
        ]
        for item_id in self.order:
            it = self.items[item_id]
            out.append(
                f"| [{item_id}](#{item_id}) | {it.get('status')} | {it.get('kind')} | "
                f"{it.get('risk')} | {it.get('phase')} | {', '.join(it.deps) or '—'} |"
            )
        out += ["", BOARD_END]
        return out

    def board_span(self) -> tuple[int, int]:
        try:
            return self.lines.index(BOARD_START), self.lines.index(BOARD_END)
        except ValueError:
            sys.exit("error: board markers missing")

    def write_board(self) -> None:
        s, e = self.board_span()
        self.lines[s : e + 1] = self.board()
        self.parse()

    def check(self) -> list[str]:
        errs = []
        for item_id in self.order:
            it = self.items[item_id]
            if not ID_RE.match(item_id):
                errs.append(f"{item_id}: invalid id")
            for key in REQUIRED:
                if not it.get(key):
                    errs.append(f"{item_id}: missing field '{key}'")
            status = it.get("status")
            if status and status not in STATUSES:
                errs.append(f"{item_id}: unknown status '{status}'")
            if it.get("kind") and it.get("kind") not in KINDS:
                errs.append(f"{item_id}: unknown kind '{it.get('kind')}'")
            if status == "held" and it.get("hold") in EMPTY:
                errs.append(f"{item_id}: status held needs a 'hold' reason")
            for d in it.deps:
                if d not in self.items:
                    errs.append(f"{item_id}: unknown dependency '{d}'")
                elif status == "in-flight" and not self.satisfied(d, item_id):
                    errs.append(f"{item_id}: in flight but dependency '{d}' is {self.items[d].get('status')}")
        state: dict[str, int] = {}

        def visit(node: str, trail: list[str]) -> None:
            state[node] = 1
            for d in self.items[node].deps:
                if d not in self.items:
                    continue
                if state.get(d) == 1:
                    errs.append("dependency cycle: " + " -> ".join(trail + [node, d]))
                elif not state.get(d):
                    visit(d, trail + [node])
            state[node] = 2

        for item_id in self.order:
            if not state.get(item_id):
                visit(item_id, [])
        s, e = self.board_span()
        if self.lines[s : e + 1] != self.board():
            errs.append("board is out of date: run `backlog.py board --write`")
        return errs


def today() -> str:
    return dt.date.today().isoformat()


def set_field(bl: Backlog, item_id: str, key: str, val: str) -> None:
    it = bl.items[item_id]
    for i in range(it.start + 1, it.end):
        m = FIELD_RE.match(bl.lines[i])
        if m and m.group(1) == key:
            bl.lines[i] = f"- {key}: {val}"
            bl.parse()
            return
    last = it.start
    for i in range(it.start + 1, it.end):
        if bl.lines[i].startswith("- "):
            last = i
    bl.lines.insert(last + 1, f"- {key}: {val}")
    bl.parse()


def cmd_set(bl: Backlog, item_id: str, field: str, value: str) -> None:
    bl.item(item_id)
    if not re.match(r"^[a-z][a-z0-9-]*$", field):
        sys.exit(f"error: invalid field name {field}")
    if field == "status" and value not in STATUSES:
        sys.exit(f"error: status must be one of {', '.join(STATUSES)}")
    if field == "kind" and value not in KINDS:
        sys.exit(f"error: kind must be one of {', '.join(KINDS)}")
    if field == "blocked-by" and value not in EMPTY:
        for d in [x.strip() for x in value.split(",") if x.strip()]:
            if d not in bl.items or d == item_id:
                sys.exit(f"error: invalid dependency {d}")
    set_field(bl, item_id, field, value)
    if field != "updated":
        set_field(bl, item_id, "updated", today())
    bl.write_board()


def cmd_add(bl: Backlog, args: argparse.Namespace) -> None:
    if args.id in bl.items:
        sys.exit(f"error: item {args.id} already exists")
    if not ID_RE.match(args.id):
        sys.exit("error: ids are lowercase letters, digits and hyphens")
    deps = [d.strip() for d in (args.blocked_by or "").split(",") if d.strip()]
    for d in deps:
        if d not in bl.items:
            sys.exit(f"error: unknown dependency {d}")
    if args.status not in STATUSES:
        sys.exit(f"error: status must be one of {', '.join(STATUSES)}")
    block = [
        f"### {args.id}",
        "",
        f"- title: {args.title}",
        f"- status: {args.status}",
        f"- kind: {args.kind}",
        f"- type: {args.type}",
        f"- phase: {args.phase}",
        f"- risk: {args.risk}",
        f"- blocked-by: {', '.join(deps) or '—'}",
        f"- owns: {args.owns or '—'}",
        f"- route: {args.route or '—'}",
        f"- record: `~/firstmate/data/{args.id}/`",
        f"- since: {today()}",
    ]
    if args.notes:
        block.append(f"- notes: {args.notes}")
    block.append("")
    bl.lines[bl.items_end : bl.items_end] = block
    bl.parse()
    bl.write_board()


def main() -> None:
    ap = argparse.ArgumentParser(description="Flo backlog tool")
    ap.add_argument("--file", type=Path, default=None)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check")
    sub.add_parser("ready")
    b = sub.add_parser("board")
    b.add_argument("--write", action="store_true")
    s = sub.add_parser("show")
    s.add_argument("id")
    st = sub.add_parser("set")
    st.add_argument("id")
    st.add_argument("field")
    st.add_argument("value", nargs="+")
    a = sub.add_parser("add")
    a.add_argument("id")
    a.add_argument("--title", required=True)
    a.add_argument("--kind", required=True, choices=KINDS)
    a.add_argument("--type", default="chore")
    a.add_argument("--phase", default="P0")
    a.add_argument("--risk", default="unknown")
    a.add_argument("--blocked-by", dest="blocked_by", default="")
    a.add_argument("--owns", default="")
    a.add_argument("--route", default="")
    a.add_argument("--notes", default="")
    a.add_argument("--status", default="queued")
    args = ap.parse_args()
    for name, value in vars(args).items():
        if isinstance(value, str) and ("\n" in value or "\r" in value):
            sys.exit(f"error: --{name} must be a single line")
    if getattr(args, "value", None) and any("\n" in v or "\r" in v for v in args.value):
        sys.exit("error: values must be a single line")
    bl = Backlog(args.file or default_file())

    if args.cmd == "check":
        errs = bl.check()
        for e in errs:
            print(e)
        print(f"{len(bl.items)} items; {len(errs)} problem(s)")
        sys.exit(1 if errs else 0)
    elif args.cmd == "ready":
        for it in bl.ready():
            print(f"{it.id}\t{it.get('kind')}\t{it.get('risk')}\t{it.get('title')}")
    elif args.cmd == "board":
        if args.write:
            bl.write_board()
            bl.save()
        else:
            print("\n".join(bl.board()))
    elif args.cmd == "show":
        it = bl.item(args.id)
        print("\n".join(bl.lines[it.start : it.end]).rstrip())
    elif args.cmd == "set":
        cmd_set(bl, args.id, args.field, " ".join(args.value))
        bl.save()
    elif args.cmd == "add":
        cmd_add(bl, args)
        bl.save()


if __name__ == "__main__":
    main()
